import re
def to_c(t):
    parts=re.split(r'\{(R|K|Y|B|G|DB|DG)\}',t)
    out=[]
    for i,p in enumerate(parts):
        if i%2==1: out.append(TAGS[p])
        elif p: out.append('"%s"'%p)
    return ' '.join(out)
